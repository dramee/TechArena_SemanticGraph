"""Правила разметки эталона в виде флагов.

Каждый флаг — гипотеза о том, как разметчик эталона учитывает исполнение.
Значения подтверждены открытым S0 и диагностическими сдачами на платформе.
"""

# Методы проекта, которые Jackson вызывает на клиентской стороне (внутри
# обработчика вызывающего сервиса), в эталон не входят: в S0 вызовы Jackson
# при разборе тела запроса не учитываются.
TRACE_CLIENT_JSON = False

# Рёбра calls к конструктору (`new X()`) не ставятся. Сам конструктор
# попадает в executes, только если вызывает методы проекта
# (Order#<init> вызывает OrderStatus#getCode).
DROP_CTOR_CALL_TARGETS = True
DROP_CTORS_WITHOUT_CALLS = True

# SQL ленивой коллекции, которую читает Jackson при сериализации ответа
# (вне методов проекта), в эталоне не приписывается никакому методу.
DROP_SERIALIZATION_LAZY_SQL = True

# Метод проекта, вызванный кодом библиотеки внутри метода F, получает ребро
# F -> метод, если в исходнике F есть вызов с тем же именем. Так получается
# ребро getToken -> User#getPassword при authenticate.
LIB_NAME_MATCH_EDGES = True

# Lombok-toString при логировании и конкатенации вызывает явные геттеры.
LOMBOK_TOSTRING_CALLS_GETTERS = True

# Конструктор, созданный Jackson при разборе тела запроса, входит в эталон,
# если вызывает методы проекта: RebookInfo#<init> -> StringUtils#Date2String
# (подтверждено сдачей r3: S2 и S7 стали 1.000).
JACKSON_CTORS_WITH_CALLS = True

# Метод проекта, вызванный из кода, который сгенерировал Lombok
# (toString, equals, hashCode), не получает ребра calls от внешнего метода.
LOMBOK_BREAKS_CHAIN = True
