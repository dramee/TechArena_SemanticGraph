"""Параметры гипотез разметки эталона (подтверждены диагностическими сдачами на платформе)."""
# Считать ли методы проекта, вызванные Jackson на клиентской стороне (внутри обработчика вызывающего сервиса).
# По эталону S0 вызовы Jackson при разборе тела запроса не учитываются, поэтому по умолчанию — нет.
TRACE_CLIENT_JSON = False

# Конструкторы в эталоне: рёбра calls К конструктору (`new X()`) не ставятся, а сам конструктор попадает в executes
# только как источник вызовов методов проекта (например, Order#<init> вызывает OrderStatus#getCode).
DROP_CTOR_CALL_TARGETS = True
DROP_CTORS_WITHOUT_CALLS = True

# SQL ленивой коллекции, которую читает Jackson при сериализации ответа (вне методов проекта), в эталоне не приписывается никому.
DROP_SERIALIZATION_LAZY_SQL = True

# Метод проекта, вызванный кодом библиотеки внутри метода F: в эталоне есть ребро F -> метод, если в исходнике F есть вызов
# с тем же именем (так получается getToken -> User#getPassword при authenticate).
LIB_NAME_MATCH_EDGES = True
# Lombok-toString при логировании/конкатенации вызывает явные геттеры класса.
LOMBOK_TOSTRING_CALLS_GETTERS = True

# Конструктор, созданный Jackson при разборе тела запроса, попадает в эталон, если вызывает методы проекта
# (RebookInfo#<init> -> StringUtils#Date2String; подтверждено сдачей r3: S2, S7 -> 1.000).
JACKSON_CTORS_WITH_CALLS = True

# Метод проекта, вызванный из кода, который сгенерировал Lombok (toString/equals/hashCode), не получает ребра calls от внешнего метода.
LOMBOK_BREAKS_CHAIN = True
